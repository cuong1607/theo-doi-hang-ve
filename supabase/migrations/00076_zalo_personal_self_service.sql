-- ============================================================
-- ZALO PERSONAL — self-service connection setup from the dashboard.
-- What the operator CLI (scripts/zalo-personal/admin.ts) did, now done by
-- the user in the web app, with the same rules and an audit trail:
--   zp_create_connection        a user creates a connection THEY own
--   zp_issue_worker             owner issues a worker credential (secret
--                               encrypted by the app; shown once to the owner)
--   zp_revoke_worker            owner revokes a worker (its requests → 403)
--   zp_set_connection_status    owner pauses / resumes the connection
-- Logging in to Zalo (QR) still happens on the Windows machine: no QR or
-- session ever travels through the dashboard.
--
-- Additive except one widening: the audit log's action / target_type CHECKs
-- (00074) gain the new values; existing rows stay valid. No table, column or
-- function of 00073 / 00074 changes otherwise; Zalo OA / Web untouched.
-- Same access model: service_role only; the application authorizes the actor.
-- After `db push`: NOTIFY pgrst, 'reload schema'.
-- ============================================================

ALTER TABLE public.zalo_personal_audit_log DROP CONSTRAINT IF EXISTS zalo_personal_audit_log_action_check;
ALTER TABLE public.zalo_personal_audit_log ADD CONSTRAINT zalo_personal_audit_log_action_check CHECK (action IN (
  'group.mode_changed', 'group.consent_granted', 'group.consent_withdrawn', 'access.granted', 'access.revoked',
  'connection.created', 'connection.paused', 'connection.resumed', 'worker.issued', 'worker.revoked'));
ALTER TABLE public.zalo_personal_audit_log DROP CONSTRAINT IF EXISTS zalo_personal_audit_log_target_type_check;
ALTER TABLE public.zalo_personal_audit_log ADD CONSTRAINT zalo_personal_audit_log_target_type_check CHECK (target_type IN ('group', 'grant', 'connection', 'worker'));

-- Limits per owner / connection (abuse guard; the CLI keeps no limit).
--   ≤ 3 connections per owner (active or paused)
--   ≤ 2 active workers per connection
CREATE OR REPLACE FUNCTION public.zp_create_connection(p_actor uuid, p_key text, p_direct_mode text)
RETURNS jsonb
LANGUAGE plpgsql
SET search_path = ''
AS $$
DECLARE
  v_id uuid;
  v_profile record;
BEGIN
  SELECT id, is_active, role INTO v_profile FROM public.profiles WHERE id = p_actor;
  IF NOT FOUND OR NOT v_profile.is_active OR v_profile.role NOT IN ('admin', 'staff') THEN
    RETURN jsonb_build_object('ok', false, 'error', 'actor_invalid');
  END IF;
  IF p_key IS NULL OR p_key !~ '^[a-z0-9][a-z0-9_-]{0,31}$' THEN RETURN jsonb_build_object('ok', false, 'error', 'invalid_key'); END IF;
  IF p_direct_mode IS NULL OR p_direct_mode NOT IN ('off', 'metadata') THEN
    -- storing 1-1 CONTENT stays an operator decision (CLI), never self-service
    RETURN jsonb_build_object('ok', false, 'error', 'invalid_direct_mode');
  END IF;
  PERFORM pg_advisory_xact_lock(hashtext('zp_create_connection:' || p_actor::text));
  IF (SELECT count(*) FROM public.zalo_personal_connections WHERE owner_user_id = p_actor) >= 3 THEN
    RETURN jsonb_build_object('ok', false, 'error', 'limit_reached');
  END IF;
  IF EXISTS (SELECT 1 FROM public.zalo_personal_connections WHERE connection_key = p_key) THEN
    RETURN jsonb_build_object('ok', false, 'error', 'key_taken');
  END IF;
  INSERT INTO public.zalo_personal_connections (connection_key, owner_user_id, direct_message_mode, created_by)
  VALUES (p_key, p_actor, p_direct_mode, p_actor)
  RETURNING id INTO v_id;
  INSERT INTO public.zalo_personal_audit_log (connection_id, actor_user_id, action, target_type, target_id, details)
  VALUES (v_id, p_actor, 'connection.created', 'connection', v_id, jsonb_build_object('key', p_key, 'directMode', p_direct_mode));
  RETURN jsonb_build_object('ok', true, 'id', v_id, 'key', p_key);
END;
$$;

-- p_worker_id is generated by the app BEFORE encrypting, because the
-- ciphertext is bound to it (AAD); the database only stores the ciphertext.
CREATE OR REPLACE FUNCTION public.zp_issue_worker(p_actor uuid, p_connection_id uuid, p_worker_id uuid, p_worker_key text, p_secret_ciphertext text)
RETURNS jsonb
LANGUAGE plpgsql
SET search_path = ''
AS $$
DECLARE
  c record;
BEGIN
  SELECT * INTO c FROM public.zalo_personal_connections WHERE id = p_connection_id FOR UPDATE;
  IF NOT FOUND OR c.owner_user_id IS DISTINCT FROM p_actor THEN RETURN jsonb_build_object('ok', false, 'error', 'not_found'); END IF;
  IF c.status <> 'active' THEN RETURN jsonb_build_object('ok', false, 'error', 'connection_paused'); END IF;
  IF p_worker_key IS NULL OR p_worker_key !~ '^[a-z0-9][a-z0-9_-]{2,47}$' THEN RETURN jsonb_build_object('ok', false, 'error', 'invalid_worker_key'); END IF;
  IF p_secret_ciphertext IS NULL OR p_secret_ciphertext NOT LIKE 'v1.%' THEN RETURN jsonb_build_object('ok', false, 'error', 'invalid_secret'); END IF;
  IF (SELECT count(*) FROM public.zalo_personal_workers WHERE connection_id = c.id AND status = 'active') >= 2 THEN
    RETURN jsonb_build_object('ok', false, 'error', 'limit_reached');
  END IF;
  IF EXISTS (SELECT 1 FROM public.zalo_personal_workers WHERE worker_key = p_worker_key) THEN
    RETURN jsonb_build_object('ok', false, 'error', 'key_taken');
  END IF;
  INSERT INTO public.zalo_personal_workers (id, worker_key, connection_id, secret_encrypted, created_by)
  VALUES (p_worker_id, p_worker_key, c.id, p_secret_ciphertext, p_actor);
  INSERT INTO public.zalo_personal_audit_log (connection_id, actor_user_id, action, target_type, target_id, details)
  VALUES (c.id, p_actor, 'worker.issued', 'worker', p_worker_id, jsonb_build_object('workerKey', p_worker_key));
  RETURN jsonb_build_object('ok', true, 'id', p_worker_id, 'workerKey', p_worker_key);
END;
$$;

CREATE OR REPLACE FUNCTION public.zp_revoke_worker(p_actor uuid, p_connection_id uuid, p_worker_id uuid)
RETURNS jsonb
LANGUAGE plpgsql
SET search_path = ''
AS $$
DECLARE
  w record;
BEGIN
  SELECT wk.* INTO w FROM public.zalo_personal_workers wk
  JOIN public.zalo_personal_connections c ON c.id = wk.connection_id
  WHERE wk.id = p_worker_id AND wk.connection_id = p_connection_id AND c.owner_user_id = p_actor
  FOR UPDATE OF wk;
  IF NOT FOUND THEN RETURN jsonb_build_object('ok', false, 'error', 'not_found'); END IF;
  IF w.status = 'revoked' THEN RETURN jsonb_build_object('ok', true, 'changed', false); END IF;
  UPDATE public.zalo_personal_workers SET status = 'revoked', revoked_at = now(), updated_at = now() WHERE id = w.id;
  INSERT INTO public.zalo_personal_audit_log (connection_id, actor_user_id, action, target_type, target_id, details)
  VALUES (p_connection_id, p_actor, 'worker.revoked', 'worker', w.id, jsonb_build_object('workerKey', w.worker_key));
  RETURN jsonb_build_object('ok', true, 'changed', true);
END;
$$;

-- Pausing = the server rejects every event / heartbeat of this connection
-- (Phase 02 ingestion checks status). Data already stored stays.
CREATE OR REPLACE FUNCTION public.zp_set_connection_status(p_actor uuid, p_connection_id uuid, p_status text)
RETURNS jsonb
LANGUAGE plpgsql
SET search_path = ''
AS $$
DECLARE
  c record;
BEGIN
  IF p_status NOT IN ('active', 'disabled') THEN RETURN jsonb_build_object('ok', false, 'error', 'invalid_status'); END IF;
  SELECT * INTO c FROM public.zalo_personal_connections WHERE id = p_connection_id FOR UPDATE;
  IF NOT FOUND OR c.owner_user_id IS DISTINCT FROM p_actor THEN RETURN jsonb_build_object('ok', false, 'error', 'not_found'); END IF;
  IF c.status = p_status THEN RETURN jsonb_build_object('ok', true, 'changed', false); END IF;
  UPDATE public.zalo_personal_connections SET status = p_status, updated_at = now() WHERE id = c.id;
  INSERT INTO public.zalo_personal_audit_log (connection_id, actor_user_id, action, target_type, target_id, details)
  VALUES (c.id, p_actor, CASE WHEN p_status = 'disabled' THEN 'connection.paused' ELSE 'connection.resumed' END, 'connection', c.id, '{}'::jsonb);
  RETURN jsonb_build_object('ok', true, 'changed', true);
END;
$$;

REVOKE EXECUTE ON FUNCTION public.zp_create_connection(uuid, text, text) FROM PUBLIC, anon, authenticated;
REVOKE EXECUTE ON FUNCTION public.zp_issue_worker(uuid, uuid, uuid, text, text) FROM PUBLIC, anon, authenticated;
REVOKE EXECUTE ON FUNCTION public.zp_revoke_worker(uuid, uuid, uuid) FROM PUBLIC, anon, authenticated;
REVOKE EXECUTE ON FUNCTION public.zp_set_connection_status(uuid, uuid, text) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.zp_create_connection(uuid, text, text) TO service_role;
GRANT EXECUTE ON FUNCTION public.zp_issue_worker(uuid, uuid, uuid, text, text) TO service_role;
GRANT EXECUTE ON FUNCTION public.zp_revoke_worker(uuid, uuid, uuid) TO service_role;
GRANT EXECUTE ON FUNCTION public.zp_set_connection_status(uuid, uuid, text) TO service_role;

